options(device=function(...) grDevices::pdf(NULL)); library(cellstyle); library(ggplot2)
d <- data.frame(x=c(0,.1,0,3,3.1,3,6,6.1,6),y=c(0,0,.1,3,3,3.1,0,0,.1),leiden=factor(c(0,0,0,4,4,4,9,9,9)))
p <- cluster_outlines(d,"x","y","leiden",clusters=c("9","4"),grid_size=40)
closed <- vapply(split(seq_len(nrow(p)),paste(p$cluster,p$path)),function(i) p$x[i[1]]==p$x[i[length(i)]] && p$y[i[1]]==p$y[i[length(i)]],logical(1))
stopifnot(identical(unique(p$cluster),c("9","4")),all(c("cluster","path","x","y") %in% names(p)),all(closed))
stopifnot(inherits(ggplot(d,aes(x,y))+geom_point()+geom_cluster_outline(p),"ggplot"))
native <- ggplot(d,aes(x,y,colour=leiden))+geom_point()+geom_cluster_outline(aes(group=leiden),clusters="4",grid_size=40)
built <- ggplot_build(native)
stopifnot(inherits(native,"ggplot"), nrow(built$data[[2]]) > 0, all(built$data[[2]]$group == 1))
bad <- data.frame(x=1:2,y=1:2,g="A")
stopifnot(nrow(suppressWarnings(cluster_outlines(bad,"x","y","g",grid_size=40)))==0L)
named <- ggplot(d, aes(x,y)) + geom_point() + geom_cluster_outline(mapping=aes(group=leiden), clusters="9")
stopifnot(identical(unique(named$layers[[2]]$data$cluster), "9"))
stopifnot(identical(unique(geom_cluster_outline(p, clusters="4")$data$cluster), "4"))
left <- expand.grid(x=seq(0,.4,length.out=5),y=seq(0,.4,length.out=5)); left$leiden <- "A"
right <- expand.grid(x=seq(.6,1,length.out=5),y=seq(0,.4,length.out=5)); right$leiden <- "B"
adjacent <- rbind(left,right)
territory_all <- suppressWarnings(cluster_outlines(adjacent,"x","y","leiden",method="territory",grid_size=40))
territory_a <- suppressWarnings(cluster_outlines(adjacent,"x","y","leiden",clusters="A",method="territory",grid_size=40))
stopifnot(all(territory_a$cluster=="A"), isTRUE(all.equal(territory_a[,c("x","y")],territory_all[territory_all$cluster=="A",c("x","y")])))
native_territory <- ggplot(adjacent,aes(x,y,colour=leiden))+geom_point()+geom_cluster_outline(aes(group=leiden),method="territory",grid_size=40)
stopifnot(inherits(native_territory,"ggplot"))
ties <- rbind(transform(left, leiden = "A"), transform(left, leiden = "B"))
tied_territory <- suppressWarnings(cluster_outlines(ties, "x", "y", "leiden", method = "territory", grid_size = 40))
stopifnot(!nrow(tied_territory))
